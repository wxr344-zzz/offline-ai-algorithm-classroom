"""从 Pydantic 导出公开 JSON Schema 与 TypeScript；--check 校验产物同步。"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lab_contracts import GenerateRequest, PublicCourse, GeneratedCourse  # noqa: E402
from teaching_assets import ClassroomTeaching  # noqa: E402


def ts_type(schema: dict[str, Any]) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    variants = schema.get("anyOf", schema.get("oneOf"))
    if variants is not None:
        return " | ".join(dict.fromkeys(ts_type(variant) for variant in variants))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            return "{ " + " ".join(
                f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
                for name, value in schema["properties"].items()
            ) + " }"
        additional = schema.get("additionalProperties", True)
        return "{ [key: string]: " + (ts_type(additional) if isinstance(additional, dict) else "unknown" if additional else "never") + " }"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return {"string": "string", "boolean": "boolean", "null": "null"}[kind]
    raise ValueError(f"不支持的 Schema 结构：{schema}")


def typescript(schemas: dict[str, Any]) -> str:
    definitions: dict[str, Any] = {}
    for schema in schemas.values():
        for name, definition in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Schema 定义冲突：{name}")
            definitions[name] = definition
    definitions.update(schemas)
    lines = [
        "// Generated by scripts/export_lab_contracts.py. Do not edit manually.",
        "// Runtime constraints are defined by contracts/*.schema.json.", "",
    ]
    for name, definition in sorted(definitions.items()):
        lines.append("// prettier-ignore")
        if definition.get("type") == "object" and "properties" in definition:
            required = set(definition.get("required", []))
            lines.append(f"export interface {name} {{")
            lines.extend(
                f"  {property_name}{'' if property_name in required else '?'}: {ts_type(value)};"
                for property_name, value in definition["properties"].items()
            )
            lines.extend(["}", ""])
        else:
            lines.extend([f"export type {name} = {ts_type(definition)};", ""])
    return "\n".join(lines)


def export(check: bool = False) -> None:
    schemas = {"GenerateRequest": GenerateRequest.model_json_schema(), "PublicCourse": PublicCourse.model_json_schema(mode="serialization")}
    internal = GeneratedCourse.model_json_schema(mode="serialization")
    teaching = ClassroomTeaching.model_json_schema(mode="serialization")
    artifacts = {
        ROOT / "contracts/eduplus-request.schema.json": json.dumps(schemas["GenerateRequest"], ensure_ascii=False, indent=2) + "\n",
        ROOT / "contracts/eduplus-public.schema.json": json.dumps(schemas["PublicCourse"], ensure_ascii=False, indent=2) + "\n",
        ROOT / "lib/types/eduplus.generated.ts": typescript(schemas),
        ROOT / "contracts/eduplus-internal.schema.json": json.dumps(internal, ensure_ascii=False, indent=2) + "\n",
        ROOT / "lib/server/eduplus-internal.generated.ts": typescript({"GeneratedCourse": internal}),
        ROOT / "contracts/eduplus-teaching.schema.json": json.dumps(teaching, ensure_ascii=False, indent=2) + "\n",
        ROOT / "lib/types/eduplus-teaching.generated.ts": typescript({"ClassroomTeaching": teaching}),
    }
    for path, content in artifacts.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise ValueError(f"契约产物未同步：{path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print("Contract artifacts are synchronized" if check else "Exported public schemas and TypeScript")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    export(parser.parse_args().check)
